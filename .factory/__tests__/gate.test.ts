import { STRICT_POLICY } from '../policy-engine';
import { checkEvidence, section } from '../gate/evidence';
import { lintPr, renderSummary } from '../gate/pr-lint';
import { lintProse, stripNonProse } from '../gate/prose-lint';

const policy = { ...STRICT_POLICY, protected_paths: ['.github/**'] };
const GOOD_BODY = '## What\nChanges a thing.\n\n## Testing\n- `npm test`: 231 pass\n\n## Rollback\nRevert the merge commit, nothing else depends on it.';

describe('lintProse', () => {
  it('errors on attribution lines in any form', () => {
    for (const t of [
      'Generated with [Claude Code](https://claude.com/claude-code)',
      '_Generated by [Claude Code](https://claude.ai/code/session_01FUM1FgvvgLHtbWhhS2Zr7D)_',
      'Co-Authored-By: Claude <noreply@anthropic.com>',
      'see https://claude.ai/code/session_01FUM1FgvvgLHtbWhhS2Zr7D'
    ]) {
      expect(lintProse(t).some(v => v.rule === 'attribution' && v.severity === 'error')).toBe(true);
    }
  });
  it('warns on AI tells', () => {
    const rules = (t: string) => lintProse(t).map(v => v.rule);
    expect(rules('It works — mostly')).toContain('em-dash');
    expect(rules('I hope this helps!')).toContain('chatbot-phrase');
    expect(rules("It's worth noting that")).toContain('filler');
    expect(rules('A seamless, cutting-edge flow')).toContain('puffery');
  });
  it('passes plain text', () => {
    expect(lintProse('Fix the retry loop so it stops after three attempts.')).toEqual([]);
  });
  it('ignores code, inline code and html comments', () => {
    const text = 'Use `delve` here.\n```\nGenerated with Claude Code — sample\n```\n<!-- seamless -->';
    expect(lintProse(text)).toEqual([]);
    expect(stripNonProse(text)).not.toContain('delve');
  });
});

describe('checkEvidence', () => {
  it('R0 needs nothing', () => {
    expect(checkEvidence('', 'R0')).toEqual([]);
  });
  it('R1 needs a substantive Testing section', () => {
    expect(checkEvidence('## What\nx', 'R1')[0].rule).toBe('evidence-missing');
    expect(checkEvidence('## Testing\nTODO', 'R1')[0].rule).toBe('evidence-missing');
    expect(checkEvidence('## Testing\nran the unit tests locally, all good', 'R1')).toEqual([]);
    expect(checkEvidence('## How it was verified\nran the unit tests locally, all good', 'R1')).toEqual([]);
  });
  it('R2 needs a concrete check; R3 also needs Rollback', () => {
    expect(checkEvidence('## Testing\nlooked at it and it seems fine to me', 'R2')[0].rule).toBe('evidence-vague');
    expect(checkEvidence('## Testing\n`npm test` passes', 'R2')).toEqual([]);
    expect(checkEvidence('## Testing\n`npm test` passes', 'R3').map(i => i.rule)).toEqual(['rollback-missing']);
    expect(checkEvidence(GOOD_BODY, 'R3')).toEqual([]);
  });
  it('reads the section until the next heading', () => {
    expect(section('## A\none\n## B\ntwo', /^b$/i)).toBe('two');
    expect(section('## A\none', /^b$/i)).toBeNull();
  });
});

describe('lintPr', () => {
  const base = { title: 'fix: stop retry loop', body: GOOD_BODY, commits: ['fix: stop retry loop'], policy };

  it('is clean for a small documented change', () => {
    const r = lintPr({ ...base, files: ['src/a.ts'], changedLines: 10 });
    expect(r.tier).toBe('R1');
    expect(r.errors).toEqual([]);
    expect(r.warnings).toEqual([]);
    expect(renderSummary(r)).toContain('No issues.');
  });
  it('fails on attribution in the body or a commit and names where', () => {
    const r = lintPr({
      ...base, files: ['src/a.ts'], changedLines: 10,
      body: GOOD_BODY + '\n\n_Generated by [Claude Code](https://claude.ai/code/session_01FUM1FgvvgLHtbWhhS2Zr7D)_',
      commits: ['fix: x', 'feat: y\n\nCo-Authored-By: Claude <noreply@anthropic.com>']
    });
    expect(r.errors.some(e => e.startsWith('body: attribution'))).toBe(true);
    expect(r.errors.some(e => e.startsWith('commit 2: attribution'))).toBe(true);
  });
  it('reports missing evidence as a warning scaled to the tier', () => {
    const r = lintPr({ ...base, body: '## What\nx', files: ['.github/workflows/a.yml'], changedLines: 5 });
    expect(r.tier).toBe('R3');
    expect(r.errors).toEqual([]);
    expect(r.warnings.some(w => w.startsWith('evidence-missing'))).toBe(true);
  });
  it('docs-only changes need no evidence', () => {
    const r = lintPr({ ...base, body: '## What\ndocs', files: ['README.md'], changedLines: 5 });
    expect(r.tier).toBe('R0');
    expect(r.warnings).toEqual([]);
  });
});

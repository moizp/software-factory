const norm = key;

/** A style by its name or any alias, ignoring case, spaces and hyphens. */
export function findStyle(name: string): Style | undefined {
  const key = norm(name);
  if (!key) return undefined;
  return CATALOGUE.find(st => norm(st.name) === key || st.aliases.some(a => norm(a) === key));
}

/** The styles that share the most feelings with the ones asked for, best first. Ties keep catalogue order. */
export function shortlist(feel: Feel[], count = 5): Array<{ style: Style; matched: Feel[] }> {
  const wanted = new Set(feel);
  return CATALOGUE
    .map((style, index) => ({ style, index, matched: style.feel.filter(f => wanted.has(f)) }))
    .filter(r => r.matched.length > 0)
    .sort((a, b) => b.matched.length - a.matched.length || a.index - b.index)
    .slice(0, count)
    .map(({ style, matched }) => ({ style, matched }));
}
